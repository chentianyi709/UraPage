import CoreGraphics

/// 工具栏按钮的方形尺寸。
///
/// 只给两处用：菜单按钮（UIKit 视图在 `sizeThatFits` 里自己报告尺寸，否则会被工具栏撑成一条）
/// 与筛选菜单的加载占位（两者同尺寸，菜单出现时工具栏不左右跳）。
/// 普通图标按钮（收藏、重试、阅读设置等）不套这个方框，交给工具栏按默认尺寸排。
///
/// 为什么是 36：导航栏给工具栏项画的玻璃底是「内容 + 8pt，且不小于 44×44」，
/// 内容一超过 36 就超出底面的 44pt 高度、被压成横向椭圆。逐像素实测：
/// 30/34/36 → 44×44 正圆，37 → 45×44，38 → 46×44，44 → 52×44。
/// 36 是仍然正圆的最大值，命中区也就用满这 44pt 的圆。
enum ToolbarControlMetrics {
    static let side: CGFloat = 36
}
