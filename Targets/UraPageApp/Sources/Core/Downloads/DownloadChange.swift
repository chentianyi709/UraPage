/// 下载管理器向界面推送的变更事件：单调递增的结构版本 + 触发本次事件的作品进度快照。
///
/// `revision` 在作品集合、任一作品或章节状态变化时递增，并随**每条**事件下发（含逐页进度事件）。
/// 由于版本单调、且后到事件携带的版本只会更大，`AsyncStream` 的 `bufferingNewest(1)` 丢弃中间事件
/// 也不会丢结构变化：消费方只要发现版本与自身已应用的不同，就重新读取状态即可收敛。
/// `progress` 只用于可以直接套用的展示（列表卡片百分比、完成提示），不承担结构语义。
struct DownloadChange: Sendable {
    /// 结构版本；与消费方已应用的版本不同时说明需要重新读取作品／章节状态。
    let revision: UInt64

    /// 触发本次事件的作品进度快照；纯结构变化时为 `nil`。
    let progress: DownloadedComicSummary?
}
